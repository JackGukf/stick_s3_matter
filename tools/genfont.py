first, last = 0x20, 0x7E
rows = []
for code in range(first, last + 1):
    ch = chr(code)
    art = G[ch]
    lines = art.split('|')
    assert len(lines) == 7, ch
    vals = []
    for ln in lines:
        assert len(ln) == 5 and set(ln) <= {'#', '.'}, (ch, ln)
        v = 0
        for i, px in enumerate(ln):
            if px == '#':
                v |= 1 << (4 - i)
        vals.append(v)
    rows.append((code, ch, vals))

